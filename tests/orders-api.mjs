import assert from 'node:assert/strict';
import { execFileSync, spawn } from 'node:child_process';
import { randomBytes, scryptSync } from 'node:crypto';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { receiptSchema, orderListSchema, adminOrderSchema, cashListSchema, summarySchema, shopSchema } from '../shared/orders.ts';

const state = await mkdtemp(join(tmpdir(), '3t-orders-api-'));
const base = 'http://127.0.0.1:8789';
const wrangler = resolve('node_modules/wrangler/bin/wrangler.js');
const env = { ...process.env, WRANGLER_LOG_PATH: join(state, 'wrangler.log'), WRANGLER_SEND_METRICS: 'false' };
const password = 'isolated-test-password-only';
const salt = randomBytes(16).toString('hex');
const digest = scryptSync(password, salt, 32, { N: 32768, r: 8, p: 3, maxmem: 64 * 1024 * 1024 }).toString('hex');
const config = JSON.parse(await readFile('wrangler.jsonc', 'utf8'));
config.main = resolve('worker/index.js');
config.assets.directory = resolve('dist');
config.d1_databases[0].migrations_dir = resolve('migrations');
config.vars = { ADMIN_USERNAME: 'test-manager', ADMIN_PASSWORD_HASH: `scrypt$32768$8$3$${salt}$${digest}`, LOCAL_ADMIN_DEV: 'true' };
const configPath = join(state, 'wrangler.json');
await writeFile(configPath, JSON.stringify(config));
let server;
let logs = '';
try {
  execFileSync(process.execPath, [wrangler, 'd1', 'migrations', 'apply', 'REVIEWS_DB', '--local', '--persist-to', state, '--config', configPath], { env, stdio: 'pipe' });
  server = spawn(process.execPath, [wrangler, 'dev', '--ip', '127.0.0.1', '--port', '8789', '--inspector-port', '9238', '--persist-to', state, '--config', configPath], { env, stdio: ['ignore', 'pipe', 'pipe'] });
  server.stdout.on('data', data => { logs += data; });
  server.stderr.on('data', data => { logs += data; });
  let ready = false;
  for (let i = 0; i < 100; i++) {
    try { ready = (await fetch(`${base}/api/shop`)).ok; } catch {}
    if (ready) break;
    await new Promise(resolve => setTimeout(resolve, 200));
  }
  assert.ok(ready, `Worker starts: ${logs}`);
  let cookie = '';
  const api = (path, data, method = 'POST', headers = {}) => fetch(`${base}/api${path}`, { method, headers: { Origin: base, 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}), ...headers }, ...(data !== undefined ? { body: JSON.stringify(data) } : {}) });
  const read = async path => (await api(path, undefined, 'GET')).json();
  const jsonOk = async (response, status = 200) => { const body = await response.json(); assert.equal(response.status, status, JSON.stringify(body)); return body; };
  const draft = { service: 'yogurt', contact: { name: 'Private customer', phone: '+60123456789' }, notes: 'Private note', consent: true, items: [{ flavorId: 'mango', quantity: 5 }], fulfillment: { method: 'delivery', address: 'TVETMARA Besut block A room 10' } };
  const attempt = () => ({ submissionId: crypto.randomUUID(), trackingKey: randomBytes(32).toString('hex'), draft });
  assert.equal((await api('/admin/orders', undefined, 'GET')).status, 401);
  assert.equal((await api('/orders', attempt(), 'POST', { Origin: 'https://evil.test' })).status, 403);
  assert.equal((await api('/orders', attempt(), 'POST', { Origin: '' })).status, 403);
  assert.equal((await api('/orders', { ...attempt(), draft: { ...draft, totalSen: 1 } })).status, 400);
  assert.equal((await api('/orders', { ...attempt(), draft: { ...draft, items: [{ flavorId: 'mango', quantity: 4 }] } })).status, 400);
  assert.equal((await api('/orders', { ...attempt(), draft: { ...draft, notes: 'x'.repeat(17000) } })).status, 413);
  const submission = attempt();
  const first = await jsonOk(await api('/orders', submission), 201);
  receiptSchema.parse(first);
  shopSchema.parse(await read('/shop'));
  assert.equal(first.order.totalSen, 1000);
  assert.equal(first.order.paidSen, 0);
  assert.equal(first.order.events.length, 1);
  assert.equal(first.order.status, 'received');
  assert.deepEqual(await jsonOk(await api('/orders', submission)), first);
  assert.equal((await api('/orders', { ...submission, draft: { ...draft, notes: 'changed' } })).status, 409);
  assert.equal((await api('/orders', { ...submission, trackingKey: randomBytes(32).toString('hex') })).status, 409);
  const racing = attempt();
  const race = await Promise.all([api('/orders', racing), api('/orders', racing)]);
  const raced = await Promise.all(race.map(r => r.json()));
  assert.equal(raced[0].order.reference, raced[1].order.reference, 'Concurrent submissions create one order');
  const track = { reference: first.order.reference, trackingKey: submission.trackingKey };
  assert.deepEqual(await jsonOk(await api('/orders/track', track)), first);
  const publicText = JSON.stringify(first);
  for (const secret of ['Private customer', '+60123456789', 'Private note', 'block A room 10', submission.trackingKey]) assert.ok(!publicText.includes(secret));
  assert.equal((await api('/orders/track', { ...track, trackingKey: '0'.repeat(64) })).status, 404);
  assert.equal((await api('/orders/track', { ...track, reference: '3T-000000000000' })).status, 404);
  const pickup = await jsonOk(await api('/orders', { ...attempt(), draft: { ...draft, items: [{ flavorId: 'mango', quantity: 1 }], fulfillment: { method: 'pickup' } } }), 201);
  assert.equal(pickup.order.totalSen, 180);
  const topup = { service: 'topup', contact: draft.contact, notes: '', consent: true, gameSlug: 'mobile-legends-my', packageId: 0, uid: '12345678', server: '1234' };
  assert.equal((await api('/orders', { ...attempt(), draft: { ...topup, server: '' } })).status, 400);
  assert.equal((await api('/orders', { ...attempt(), draft: { ...topup, gameSlug: 'unknown' } })).status, 400);
  const topupOrder = await jsonOk(await api('/orders', { ...attempt(), draft: topup }), 201);
  assert.equal(topupOrder.order.totalSen, null);
  const repair = await jsonOk(await api('/orders', { ...attempt(), draft: { service: 'repair', contact: draft.contact, notes: '', consent: true, brand: 'Apple', model: 'iPhone 13', issue: 'Battery' } }), 201);
  assert.equal(repair.order.totalSen, null);
  assert.equal((await api('/admin/login', { username: 'test-manager', password: 'wrong' })).status, 401);
  const login = await api('/admin/login', { username: 'test-manager', password });
  assert.deepEqual(await jsonOk(login), { username: 'test-manager' });
  const setCookie = login.headers.get('set-cookie');
  assert.match(setCookie, /HttpOnly/);
  assert.match(setCookie, /SameSite=Strict/);
  cookie = setCookie.split(';')[0];
  assert.deepEqual(await read('/admin/session'), { username: 'test-manager' });
  const list = await read('/admin/orders');
  orderListSchema.parse(list);
  assert.equal(list.total, 5, 'Racing retry does not duplicate');
  assert.equal((await read('/admin/orders?service=topup')).total, 1);
  assert.equal((await read('/admin/orders?q=Private')).total, 5);
  assert.equal((await api('/admin/orders?page=-1', undefined, 'GET')).status, 400);
  let order = await read(`/admin/orders/${track.reference}`);
  adminOrderSchema.parse(order);
  assert.equal(order.draft.contact.name, 'Private customer');
  const update = { version: order.version, status: 'confirmed', totalSen: 1000, internalNote: 'Manager only', message: 'Your order is confirmed.' };
  const updates = await Promise.all([api(`/admin/orders/${track.reference}`, update, 'PATCH'), api(`/admin/orders/${track.reference}`, { ...update, message: 'Conflicting update' }, 'PATCH')]);
  assert.deepEqual(updates.map(r => r.status).sort(), [200, 409]);
  order = await read(`/admin/orders/${track.reference}`);
  assert.equal(order.version, 2);
  assert.equal(order.events.length, 2, 'Only the successful change appends history');
  assert.equal((await api(`/admin/orders/${track.reference}`, { ...update, version: 2, status: 'completed' }, 'PATCH')).status, 400);
  const entry = (kind, amountSen) => ({ submissionId: crypto.randomUUID(), kind, amountSen, occurredOn: '2026-10-12', note: 'Test cash record', ...(['payment', 'refund'].includes(kind) ? { orderReference: track.reference } : {}) });
  const paymentInput = entry('payment', 1000);
  const payment = await jsonOk(await api('/admin/ledger', paymentInput), 201);
  assert.deepEqual(await jsonOk(await api('/admin/ledger', paymentInput)), payment);
  assert.equal((await api('/admin/ledger', { ...paymentInput, amountSen: 900 })).status, 409);
  assert.equal((await api('/admin/ledger', { ...entry('income', 100), orderReference: track.reference })).status, 400);
  assert.equal((await api('/admin/ledger', { ...entry('income', 100), occurredOn: '2026-02-30' })).status, 400);
  assert.equal((await api('/admin/ledger', { ...entry('income', 100), occurredOn: '2026-99-12' })).status, 400);
  assert.equal((await api('/admin/summary?from=2026-99-12', undefined, 'GET')).status, 400);
  assert.equal((await api('/admin/ledger', entry('expense', 0))).status, 400);
  const refund = await jsonOk(await api('/admin/ledger', entry('refund', 200)), 201);
  const incomeAttempt = entry('income', 500);
  const cashRace = await Promise.all([api('/admin/ledger', incomeAttempt), api('/admin/ledger', incomeAttempt)]);
  assert.equal((await cashRace[0].json()).id, (await cashRace[1].json()).id);
  await jsonOk(await api('/admin/ledger', entry('expense', 300)), 201);
  let totals = await read('/admin/summary?from=2026-10-12&to=2026-10-12');
  summarySchema.parse(totals);
  assert.equal(totals.incomeSen, 1500);
  assert.equal(totals.expenseSen, 500);
  assert.equal(totals.netSen, 1000);
  assert.equal((await jsonOk(await api('/orders/track', track))).order.paidSen, 800);
  const voided = await jsonOk(await api(`/admin/ledger/${refund.id}/void`, { reason: 'Refund recorded by mistake' }));
  assert.deepEqual(await jsonOk(await api(`/admin/ledger/${refund.id}/void`, { reason: 'Retry' })), voided);
  totals = await read('/admin/summary?from=2026-10-12&to=2026-10-12');
  assert.equal(totals.netSen, 1200);
  assert.equal((await jsonOk(await api('/orders/track', track))).order.paidSen, 1000);
  const cashList = await read('/admin/ledger');
  cashListSchema.parse(cashList);
  assert.equal(cashList.total, 4);
  assert.equal((await read('/admin/summary?from=2026-10-13&to=2026-10-13')).netSen, 0);
  const qr = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6nmgAAAAASUVORK5CYII=';
  assert.equal((await api('/admin/payment-settings', { qrDataUrl: 'data:image/png;base64,SGVsbG8=', instructions: '' }, 'PUT')).status, 400);
  assert.equal((await api('/admin/payment-settings', { qrDataUrl: 'data:image/svg+xml;base64,PHN2Zz4=', instructions: '' }, 'PUT')).status, 400);
  await jsonOk(await api('/admin/payment-settings', { qrDataUrl: qr, instructions: 'Use your order reference.' }, 'PUT'));
  assert.equal((await read('/shop')).qrDataUrl, qr);
  execFileSync(process.execPath, [wrangler, 'd1', 'execute', 'REVIEWS_DB', '--local', '--persist-to', state, '--config', configPath, '--command', "UPDATE admin_sessions SET credential_hash = 'old-credential'"], { env, stdio: 'pipe' });
  assert.equal((await api('/admin/session', undefined, 'GET')).status, 401, 'Credential rotation invalidates old sessions');
  const freshLogin = await api('/admin/login', { username: 'test-manager', password });
  await jsonOk(freshLogin);
  cookie = freshLogin.headers.get('set-cookie').split(';')[0];
  await jsonOk(await api('/admin/logout', {}));
  assert.equal((await api('/admin/session', undefined, 'GET')).status, 401);
  cookie = '';
  for (let i = 0; i < 9; i++) await api('/admin/login', { username: 'test-manager', password: 'wrong' });
  assert.equal((await api('/admin/login', { username: 'test-manager', password })).status, 429);
  for (let i = 0; i < 61; i++) await api('/orders/track', track);
  assert.equal((await api('/orders/track', track)).status, 429, 'Tracking is rate limited');
  for (let i = 0; i < 20; i++) await api('/orders', attempt());
  assert.equal((await api('/orders', attempt())).status, 429, 'New orders are rate limited');
  assert.equal((await api('/orders', submission)).status, 200, 'Existing submission can retry after rate limit');
  assert.equal((await fetch(`${base}/api/reviews`)).status, 200, 'Reviews remain available');
  console.log('Orders API passed: auth, scrypt runtime, privacy, retries, races, pricing, transitions, ledger, voids, summaries and QR validation.');
} catch (error) {
  console.error(logs.slice(-12000));
  throw error;
} finally {
  server?.kill('SIGTERM');
  if (server) await new Promise(resolve => { server.once('exit', resolve); setTimeout(resolve, 2000); });
  await rm(state, { recursive: true, force: true });
}
